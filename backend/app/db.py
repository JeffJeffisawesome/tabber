"""SQLite database configuration, connection management, and seed data."""

import sqlite3
import os
from pathlib import Path
from datetime import datetime, timezone
from typing import Optional, List, Dict, Any

# Place tabs.db in the backend folder
DB_PATH = Path(__file__).resolve().parent.parent / "tabs.db"


def get_db_connection() -> sqlite3.Connection:
    """Return a connection with dictionary-like row access."""
    conn = sqlite3.connect(str(DB_PATH))
    conn.row_factory = sqlite3.Row
    return conn


def init_db() -> None:
    """Create tables if they don't exist and seed starter guitar tabs."""
    with get_db_connection() as conn:
        cursor = conn.cursor()
        cursor.execute(
            """
            CREATE TABLE IF NOT EXISTS tabs (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                title TEXT NOT NULL,
                artist TEXT NOT NULL,
                tuning TEXT NOT NULL DEFAULT 'Standard (E A D G B E)',
                capo INTEGER DEFAULT 0,
                difficulty TEXT NOT NULL DEFAULT 'Intermediate',
                content TEXT NOT NULL,
                is_favorite BOOLEAN NOT NULL DEFAULT 0,
                created_at TEXT NOT NULL,
                updated_at TEXT NOT NULL
            );
            """
        )

        # Check if table is empty; if so, populate with classic tabs
        cursor.execute("SELECT COUNT(*) as count FROM tabs;")
        if cursor.fetchone()["count"] == 0:
            seed_tabs(cursor)
        conn.commit()


